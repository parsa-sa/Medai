function Frame28() {
  const [currentSlide, setCurrentSlide] = useState(0);
  const [touchStart, setTouchStart] = useState<number | null>(null);
  const [touchEnd, setTouchEnd] = useState<number | null>(null);

  const minSwipeDistance = 50;

  const goToNext = () => {
    setCurrentSlide((prev) => (prev < 3 ? prev + 1 : 0));
  };

  const goToPrev = () => {
    setCurrentSlide((prev) => (prev > 0 ? prev - 1 : 3));
  };

  const onTouchStart = (e: React.TouchEvent) => {
    setTouchEnd(null);
    setTouchStart(e.targetTouches[0].clientX);
  };

  const onTouchMove = (e: React.TouchEvent) => {
    setTouchEnd(e.targetTouches[0].clientX);
  };

  const onTouchEnd = () => {
    if (!touchStart || !touchEnd) return;

    const distance = touchStart - touchEnd;
    const isLeftSwipe = distance > minSwipeDistance;
    const isRightSwipe = distance < -minSwipeDistance;

    if (isLeftSwipe) {
      goToNext();
    } else if (isRightSwipe) {
      goToPrev();
    }
  };

  return (
    <div
      className="content-stretch flex flex-col gap-[24px] items-start relative shrink-0 w-full"
      onTouchStart={onTouchStart}
      onTouchMove={onTouchMove}
      onTouchEnd={onTouchEnd}
    >
      <div className="w-full overflow-visible max-w-[1368px]">
        <div
          className="flex gap-[24px] transition-transform duration-500 ease-out"
          style={{
            transform: `translateX(calc(-${currentSlide} * (318px + 24px)))`
          }}
        >
          <Container25 />
        </div>
      </div>
      <Progress currentSlide={currentSlide} onNext={goToNext} onPrev={goToPrev} />
    </div>
  );
}

